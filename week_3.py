#Palindrome of number

n = int(input())
original = n
reverse = 0
while n>0:
  digit = n%10
  reverse = reverse * 10 + digit
  n = n//10
if original == reverse:
  print("Palindrome")
else:
  print("Not a palindrome")

#Reverse a number
n=int(input())
reverse = 0
while n>0:
  ld=n%10
  reverse=reverse*10+ld
  n=n//10
print(reverse)

#factorial of  a number
n = int(input())
factorial = 1
for i in range(1,n+1):
  factorial=factorial*i
print(factorial)

